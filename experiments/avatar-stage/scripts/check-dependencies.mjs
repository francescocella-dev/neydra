import assert from "node:assert/strict";
import { readFile, readdir, writeFile } from "node:fs/promises";
const root = new URL("../", import.meta.url);
const lock = JSON.parse(await readFile(new URL("package-lock.json", root)));
const allowed = new Set([
  "MIT",
  "Apache-2.0",
  "BlueOak-1.0.0",
  "ISC",
  "BSD-3-Clause",
  "Python-2.0",
  "CC-BY-4.0",
  "BSD-2-Clause",
]);
const counts = {},
  notices = [];
for (const [path, entry] of Object.entries(lock.packages)) {
  if (!path) continue;
  let pkg;
  try {
    pkg = JSON.parse(await readFile(new URL(`${path}/package.json`, root)));
  } catch (error) {
    if (error.code === "ENOENT" && entry.optional) continue;
    throw error;
  }
  const license =
    typeof pkg.license === "object" ? pkg.license.type : pkg.license;
  assert.ok(allowed.has(license), `Review license for ${pkg.name}: ${license}`);
  counts[license] = (counts[license] ?? 0) + 1;
  // Preserve notices for all runtime dependencies and CC-BY build data.
  if (!entry.dev || license === "CC-BY-4.0") {
    const files = await readdir(new URL(`${path}/`, root));
    const name = files.find((n) => /^licen[sc]e(\.(md|txt))?$/i.test(n));
    // Fiber's published npm tarball omits LICENSE. Retain the exact tag's notice.
    // Source: https://raw.githubusercontent.com/pmndrs/react-three-fiber/v9.8.2/LICENSE
    const fiberNotice =
      pkg.name === "@react-three/fiber" && pkg.version === "9.8.2";
    assert.ok(name || fiberNotice, `${pkg.name}: license notice file missing`);
    const text = await readFile(
      new URL(
        name ? `${path}/${name}` : "licenses/react-three-fiber-LICENSE.txt",
        root,
      ),
      "utf8",
    );
    notices.push(
      `## ${pkg.name} ${pkg.version}\n\n${license}${entry.dev ? " (build tooling / data only)" : " (runtime dependency)"}. Source: https://www.npmjs.com/package/${pkg.name}/v/${pkg.version}\n\n\`\`\`text\n${text.trim().replace(/\r\n/g, "\n").replace(/[ \t]+$/gm, "")}\n\`\`\`\n`,
    );
  }
}
const output =
  "# Third-party notices\n\nGenerated by `node scripts/check-dependencies.mjs --write` from the installed lockfile.\nRuntime packages and CC-BY build data notices are retained below. All installed\nlicense declarations are checked; this is a source/license check, not legal certification.\nNo service subscription, asset purchase or hosted infrastructure is required.\n\n" +
  notices.join("\n");
const target = new URL("THIRD_PARTY_NOTICES.md", root);
if (process.argv.includes("--write")) await writeFile(target, output);
else
  assert.equal(
    await readFile(target, "utf8"),
    output,
    "Dependency notices differ; regenerate and review.",
  );
console.log(
  `PASS dependency licenses: ${Object.values(counts).reduce((sum, n) => sum + n, 0)} installed packages, ${notices.length} retained notices; ${JSON.stringify(counts)}`,
);
